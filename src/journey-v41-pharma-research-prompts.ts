export function buildNotebookAnalysisPrompt(state: Pick<PharmaStrategyResearchState, 'selectedTopicId' | 'customTopic'>) {
  return `업로드한 소스만 근거로 분석해 주세요.

주제는 2026년 제약업계 전사 전략과제 "${pharmaTitleOf(state)}"입니다.

목적:
이 전략과제를 추진하기 위한 전사 추진과제 후보를 발굴하고, 각 추진과제에 맞는 CSF와 KPI를 선정하려고 합니다.

요청:
1. 소스에 근거한 핵심 변화 신호를 3개로 정리해 주세요.
2. 이 전략과제가 전사 차원에서 왜 중요한지 설명해 주세요.
3. 전사 추진과제 후보를 3~5개 발굴해 주세요. 추진과제는 실제로 실행 단위가 될 수 있게 써 주세요.
4. 각 추진과제별 CSF 후보를 정리해 주세요. CSF는 핵심 성공 요인이므로, 해당 추진과제가 성공하려면 반드시 갖춰야 할 조건으로 써 주세요.
5. 각 추진과제별 KPI 후보를 정리해 주세요. KPI는 측정 가능한 지표이므로, 비율·건수·금액·기간·달성률 등 측정 단위가 보이게 써 주세요.
6. 전사 추진계획을 세울 때 반드시 확인해야 할 쟁점을 3개만 정리해 주세요.
7. 고객 의도 단정, 처방 유도, 경쟁사 비방, 허가 외 사용 암시처럼 조심할 표현을 따로 표시해 주세요.

출력 형식:
[핵심 변화 신호]
[출처/근거 요약]
[전사 추진과제 후보]
[추진과제별 CSF 후보]
[추진과제별 KPI 후보]
[추진계획 수립 쟁점]
[주의해야 할 표현]`;
}

